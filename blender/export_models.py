"""Export the models of a mocap scene for the live view / offline renderer. Runs INSIDE Blender:

    blender -b mocap_scene.blend --python blender/export_models.py -- <assets_dir> <scene_yaml> <name>

(normally via scripts/blender_export.py). The .blend file is not modified.

What is exported (mesh objects in the "models" collection, hidden-in-render objects skipped):
  - objects without a Vicon parent        -> <assets_dir>/world.glb       static, Vicon world
  - objects parented (directly or not)    -> <assets_dir>/<subject>.glb   in the subject's frame
    to a Vicon subject Empty                 (follows the subject)
  - objects in a collection "holdouts"    -> <assets_dir>/holdouts_*.glb  invisible, hide virtual
                                             objects behind real ones
glTF is Y-up (standard); the loader converts back to the Vicon Z-up frame.
"""

import sys
from pathlib import Path

import bpy
from mathutils import Matrix

MESH_TYPES = {"MESH"}


def subject_of(obj) -> str | None:
    """Vicon subject this object hangs on (through its parent chain), or None."""
    p = obj.parent
    while p is not None:
        if "vicon_subject" in p:
            return p["vicon_subject"]
        p = p.parent
    return None


def in_holdouts(obj) -> bool:
    return any(c.name.lower().startswith("holdouts") for c in obj.users_collection)


def collect(scene):
    """{(kind, subject): [objects]} with kind 'model' or 'holdout', subject None = static."""
    models = bpy.data.collections.get("models")
    if models is None:
        raise SystemExit("no 'models' collection in this file")
    groups: dict[tuple[str, str | None], list] = {}
    for obj in models.all_objects:
        if obj.type not in MESH_TYPES or obj.hide_render:
            continue
        key = ("holdout" if in_holdouts(obj) else "model", subject_of(obj))
        groups.setdefault(key, []).append(obj)
    return groups


def export_group(objs, path: Path, subject: str | None) -> None:
    """Export objects with the subject Empty temporarily at the origin, so the file is in the
    subject's frame (static objects: Vicon world)."""
    empty, saved_action, saved_matrix = None, None, None
    if subject is not None:
        empty = next(o for o in bpy.data.objects if o.get("vicon_subject") == subject)
        if empty.animation_data:
            saved_action = empty.animation_data.action
            empty.animation_data.action = None
        saved_matrix = empty.matrix_world.copy()
        empty.matrix_world = Matrix.Identity(4)
        bpy.context.view_layer.update()
    try:
        bpy.ops.object.select_all(action="DESELECT")
        for o in objs:
            o.select_set(True)
        bpy.ops.export_scene.gltf(
            filepath=str(path), export_format="GLB", use_selection=True, export_apply=True,
            export_yup=True, export_animations=False, export_cameras=False, export_lights=False,
            export_extras=False, export_materials="EXPORT",
        )
    finally:
        if empty is not None:
            empty.matrix_world = saved_matrix
            if saved_action is not None:
                empty.animation_data.action = saved_action
            bpy.context.view_layer.update()


def scene_yaml(name: str, files: dict, assets_rel: str) -> str:
    lines = [f"# Generated by scripts/blender_export.py from {bpy.data.filepath}",
             "# Re-export to update. Edit freely: shadow, opacity, color (tint), trails.",
             f"name: {name}", "", "objects:"]
    holdouts = []
    for (kind, subject), file in sorted(files.items(), key=lambda kv: (kv[0][0], kv[0][1] or "")):
        entry = [f"  - name: {Path(file).stem}",
                 f"    mesh: {{type: gltf, file: {assets_rel}/{file}}}"]
        if subject:
            entry.append(f"    attach: {subject}")
        if kind == "holdout":
            holdouts += entry
        else:
            entry.append(f"    shadow: {'false' if subject else 'true'}")
            lines += entry
    if holdouts:
        lines += ["", "holdouts:"] + holdouts
    subjects = sorted({s for (_, s) in files if s})
    if subjects:
        lines += ["", "trails:"] + [f"  - {{subject: {s}, seconds: 3.0, color: \"#00e5ff\", width: 3}}"
                                    for s in subjects]
    return "\n".join(lines) + "\n"


def main():
    argv = sys.argv[sys.argv.index("--") + 1:]
    assets_dir, scene_path, name, assets_rel = Path(argv[0]), Path(argv[1]), argv[2], argv[3]
    scene = bpy.data.scenes.get("mocap") or bpy.context.scene
    groups = collect(scene)
    if not groups:
        raise SystemExit("nothing to export: put mesh objects into the 'models' collection")
    assets_dir.mkdir(parents=True, exist_ok=True)
    for old in assets_dir.glob("*.glb"):
        old.unlink()
    # Make "mocap" the active scene even if the file was saved while "output" was active: remove the
    # other scenes in memory (the .blend is never saved). Note: a context temp_override with scene /
    # view_layer crashes the glTF exporter in Blender 4.5.
    for other in [sc for sc in bpy.data.scenes if sc != scene]:
        bpy.data.scenes.remove(other)
    files = {}
    for (kind, subject), objs in groups.items():
        stem = subject or "world"
        file = f"{'holdouts_' if kind == 'holdout' else ''}{stem}.glb"
        export_group(objs, assets_dir / file, subject)
        files[(kind, subject)] = file
        print(f"EXPORT {file}: {len(objs)} objects ({', '.join(o.name for o in objs[:6])}"
              f"{', ...' if len(objs) > 6 else ''})")
    scene_path.parent.mkdir(parents=True, exist_ok=True)
    scene_path.write_text(scene_yaml(name, files, assets_rel))
    print(f"SCENE {scene_path}")


if __name__ == "__main__":
    main()
